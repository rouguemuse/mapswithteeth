/**
 * DESIGN INTELLIGENCE EXTRACTOR & DUAL-INDEX TOKEN COMPILER (v3.0)
 * ---------------------------------------------------------------------------
 * Compiles `src/design-intelligence/token-registry.json` into:
 *   1. AXIS 1 (By Original Architectural Archetype): `--di-<archetype>-<category>-<token>`
 *   2. AXIS 2 (By Validated Container & UX Pattern): `--pattern-<role>`
 */

import fs from 'fs';
import path from 'path';

const REGISTRY_PATH = path.resolve(process.cwd(), 'src/design-intelligence/token-registry.json');
const OUTPUT_CSS_PATH = path.resolve(process.cwd(), 'src/design-intelligence/compiled-packs.css');

function compileRegistryToCss() {
  const raw = fs.readFileSync(REGISTRY_PATH, 'utf-8');
  const registry = JSON.parse(raw);

  const lines: string[] = [
    '/* ============================================================================',
    `   ${registry.library.name} (v${registry.library.version})`,
    `   Organization: ${registry.library.organizationModel}`,
    `   IP Notice: ${registry.library.ipAndGovernanceNotice}`,
    '   Auto-Generated by scripts/extract_design_tokens.ts',
    '   ============================================================================ */',
    '',
    ':root {',
    '  /* ==========================================================================',
    '     AXIS 1: ORIGINAL ARCHITECTURAL ARCHETYPES (--di-<archetype>-<cat>-<name>)',
    '     ========================================================================== */'
  ];

  for (const [archId, arch] of Object.entries<Record<string, unknown>>(registry.archetypes)) {
    lines.push(`  /* --- ARCHETYPE: ${arch.name} (${arch.domain}) --- */`);
    const tokens = arch.tokens as Record<string, Record<string, string>>;
    for (const [cat, entries] of Object.entries(tokens)) {
      for (const [key, val] of Object.entries(entries)) {
        lines.push(`  --di-${archId}-${cat}-${key}: ${val};`);
      }
    }
    lines.push('');
  }

  lines.push('  /* ==========================================================================');
  lines.push('     AXIS 2: VALIDATED CONTAINER & UX PATTERNS (--pattern-<role>)');
  lines.push('     ========================================================================== */');

  for (const [, pattern] of Object.entries<Record<string, unknown>>(registry.patternsByPurpose)) {
    lines.push(`  /* --- ${pattern.title} --- */`);
    const vars = pattern.cssVariables as Record<string, string>;
    for (const [varName, val] of Object.entries(vars)) {
      lines.push(`  ${varName}: ${val};`);
    }
    lines.push('');
  }

  lines.push('}');
  lines.push('');

  fs.writeFileSync(OUTPUT_CSS_PATH, lines.join('\n'), 'utf-8');
  console.log(
    `Compiled ${Object.keys(registry.archetypes).length} original archetypes & ${Object.keys(registry.patternsByPurpose).length} container patterns -> ${OUTPUT_CSS_PATH}`
  );
}

compileRegistryToCss();
